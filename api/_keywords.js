/* คำเร่งด่วน — ตอบก่อนเนื้อหาหมวดอื่นทุกครั้งไม่ว่าจะแมตช์หมวดไหนด้วย
   ⚠️ เบอร์สายด่วนด้านล่างต้องให้นิติกรยืนยันว่าถูกต้อง/ใช้งานได้จริงก่อนเผยแพร่ (ดู SPEC.md ข้อ 13.2) */
export const URGENT_PATTERNS = [
  /ถูกทำร้าย/, /โดนทำร้าย/, /ทำร้ายร่างกาย/, /ถูกข่มขู่/, /จะมาทำร้าย/, /ฉุกเฉิน/, /ด่วนที่สุด/,
  /เพิ่งโอนเงิน.*(มิจฉาชีพ|โกง|หลอก)/, /(มิจฉาชีพ|โกง|หลอก).*เพิ่งโอนเงิน/,
];

export function matchUrgent(text) {
  const s = String(text || "");
  return URGENT_PATTERNS.some((re) => re.test(s));
}

export function matchTopic(text) {
  const s = String(text || "");
  return TOPICS.find((t) => t.patterns.some((re) => re.test(s))) || null;
}

export function getTopic(key) {
  return TOPICS.find((t) => t.key === key) || null;
}

export const UNREVIEWED_TOPICS = () => TOPICS.filter((t) => !t.reviewed).map((t) => t.key);
